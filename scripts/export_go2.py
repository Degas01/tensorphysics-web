"""Export the two Go2 ActuatorFit v1 studies (damping 2 and 0) to lib/data/go2.ts.

    python scripts/export_go2.py <go2_d2/results.json> <go2_d0/results.json>
"""
import json, sys

def pick(pj, i):
    return pj["fits"][i] if i is not None and pj["fits"] else None

def run(path, label, damping):
    r = json.load(open(path, encoding="utf-8"))
    joints = []
    for j in r["joints"]:
        pj = r["per_joint"][j]
        lo, rec = pick(pj, pj["lightest_nominal_index"]), pick(pj, pj["recommended_index"])
        joints.append({
            "key": j, "leg": j[:2], "part": j.split("_")[1],
            "lightest": {"name": lo["name"], "mass_kg": lo["mass_kg"], "u": lo["u"], "u_corner": lo["u_corner"], "breaks_first": lo["breaks_first"]},
            "pick": {"name": rec["name"], "mass_kg": rec["mass_kg"], "u": rec["u"], "u_corner": rec["u_corner"], "holds": rec["fits_with_margin"]},
        })
    c = r["checks"]
    return {
        "label": label, "damping": damping,
        "date": r["meta"]["date"], "elapsed_s": r["meta"]["elapsed_s"], "solves": r["meta"]["id_solves"],
        "worst_u": round(r["combined"]["worst_u"], 3),
        "checks": {"static": c["2a"]["passed"], "accel": c["2b"]["passed"], "speed": c["3"]["passed"],
                   "accel_tasks": {k: {"passed": v["passed"], "rel_err": round(v["true"]["joint_rel_err"], 5),
                                       "power": v["has_power"]} for k, v in c["2b"]["tasks"].items()},
                   "replay_diag": {k: {"joint_rad": round(v["joint_err_rad"], 4), "zero_joint_rad": round(v["zero_torque_control"]["joint_err_rad"], 4)}
                                   for k, v in r["replay_diagnostic"]["tasks"].items()}},
        "joints": joints,
        "total_pick_kg": round(sum(j["pick"]["mass_kg"] for j in joints), 2),
        "total_lightest_kg": round(sum(j["lightest"]["mass_kg"] for j in joints), 2),
    }

a, b = sys.argv[1], sys.argv[2]
data = {"tasks": [t["title"] for t in json.load(open(a))["tasks"]],
        "runs": [run(b, "Unitree's own model", 0.0), run(a, "MuJoCo Menagerie model", 2.0)]}
with open("lib/data/go2.ts", "w", encoding="utf-8") as fh:
    fh.write("// Generated by scripts/export_go2.py from TensorPhysics Main/actuatorfit/results/go2_d0 and go2_d2 (ActuatorFit v1).\n")
    fh.write("// Do not edit by hand. Torques come from planned motions on a hard floor; datasheet values are vendor claims (REPORTED);\n")
    fh.write("// every result is model-based (INFERENCE). Joint damping: 0 in Unitree's URDF, 2 N m s/rad in MuJoCo Menagerie (VERIFIED).\n\n")
    fh.write("export const go2 = " + json.dumps(data, indent=2) + " as const;\n")
print("ok")
